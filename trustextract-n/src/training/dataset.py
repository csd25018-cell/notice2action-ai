"""
dataset.py – PyTorch Dataset for TrustExtract-N Token Classification
===================================================================
Loads the pre-chunked BIO token classification data generated by convert_labels.py.
Each record in the JSONL corresponds to a fixed-length window of a document
with `input_ids`, `attention_mask`, and `label_ids`.
"""

import json
from pathlib import Path
from typing import Dict, List, Any

import torch
from torch.utils.data import Dataset


class TokenClassificationDataset(Dataset):
    """
    PyTorch dataset for BIO token classification.
    Expects JSONL files where each line has at least:
      - input_ids: List[int]
      - attention_mask: List[int]
      - label_ids: List[int]
      - document_id: str
      - chunk_index: int
    """

    def __init__(self, jsonl_path: str):
        self.jsonl_path = Path(jsonl_path)
        self.examples: List[Dict[str, Any]] = []

        if not self.jsonl_path.exists():
            raise FileNotFoundError(f"Dataset file not found: {self.jsonl_path}")

        self._load_data()

    def _load_data(self):
        with open(self.jsonl_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                obj = json.loads(line)
                
                # We store as tensors so the DataCollator can batch them efficiently
                self.examples.append({
                    "input_ids": torch.tensor(obj["input_ids"], dtype=torch.long),
                    "attention_mask": torch.tensor(obj["attention_mask"], dtype=torch.long),
                    "labels": torch.tensor(obj["label_ids"], dtype=torch.long),
                    "document_id": obj["document_id"],
                    "chunk_index": obj["chunk_index"],
                })

    def __len__(self) -> int:
        return len(self.examples)

    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        # The Trainer expects dicts with keys matching model forward() signature.
        # We omit document_id and chunk_index here because default collators 
        # try to batch all returned keys into tensors.
        example = self.examples[idx]
        return {
            "input_ids": example["input_ids"],
            "attention_mask": example["attention_mask"],
            "labels": example["labels"],
        }
